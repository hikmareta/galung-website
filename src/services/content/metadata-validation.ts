import { safeRichText } from "./rich-text.ts";
export function semanticVersion(value: unknown): true | string {
  return (
    (typeof value === "string" &&
      /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-(?:0|[1-9]\d*|\d*[A-Za-z-][0-9A-Za-z-]*)(?:\.(?:0|[1-9]\d*|\d*[A-Za-z-][0-9A-Za-z-]*))*)?(?:\+[0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*)?$/.test(
        value,
      )) ||
    "Use a semantic version"
  );
}
export function safeLink(value: unknown): true | string {
  if (value == null || value === "") return true;
  return (
    (typeof value === "string" &&
      !Array.from(value).some(
        (character) =>
          character.charCodeAt(0) <= 32 ||
          character.charCodeAt(0) === 127 ||
          character === "\\",
      ) &&
      (/^\/(?!\/)/.test(value) || /^https:\/\//.test(value))) ||
    "Use a site-relative path or HTTPS URL without control characters"
  );
}
export function validateAuthoredContent(value: unknown): true | string {
  const richFields = new Set(["content", "caseStudy", "overview"]);
  const linkFields = new Set([
    "link",
    "secondaryLink",
    "url",
    "href",
    "publicURL",
    "videoURL",
  ]);
  function checkLocalized(
    child: unknown,
    validate: (value: unknown) => true | string,
  ): true | string {
    if (
      child &&
      typeof child === "object" &&
      !("root" in child) &&
      ("id" in child || "en" in child)
    ) {
      for (const item of Object.values(child)) {
        const result = validate(item);
        if (result !== true) return result;
      }
      return true;
    }
    return validate(child);
  }
  function walk(v: unknown): true | string {
    if (!v || typeof v !== "object") return true;
    // Populated upload URLs are generated by Payload, including HTTP in local development.
    if ("mimeType" in v && "filename" in v && "id" in v) return true;
    for (const [key, child] of Object.entries(v)) {
      if (richFields.has(key)) {
        const result = checkLocalized(child, safeRichText);
        if (result !== true) return `${key}: ${result}`;
      }
      if (linkFields.has(key)) {
        const result = checkLocalized(child, safeLink);
        if (result !== true) return `${key}: ${result}`;
      }
      const result = walk(child);
      if (result !== true) return result;
    }
    return true;
  }
  return walk(value);
}
